function initialLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.has(saved)) return saved;
  } catch {}
  return navigator.language?.toLowerCase().startsWith("en") ? "en" : "es";
}

let language = initialLanguage();

export function getLanguage() { return language; }
export function locale() { return language === "en" ? "en-US" : "es-MX"; }

export function translateText(value) {
  const source = String(value ?? "");
  if (language !== "en" || !source) return source;
  const validation = source.match(/^Value error,\s*(.+)$/i);
  if (validation) return translateText(validation[1]);
  const row = source.match(/^(?:La fila|Fila) (\d+):?\s*(.+)$/i);
  if (row) return `Row ${row[1]}: ${translateText(row[2])}`;
  const transfer = source.match(/^Teléfono de transferencia (\d+):\s*(.+)$/i);
  if (transfer) return `Transfer phone ${transfer[1]}: ${translateText(transfer[2])}`;
  if (Object.hasOwn(EN, source)) return EN[source];
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(source)) return source.replace(pattern, replacement);
  }
  return source;
}

export function t(source, variables = {}) {
  let result = translateText(source);
  for (const [key, value] of Object.entries(variables)) {
    result = result.replaceAll(`{${key}}`, String(value));
  }
  return result;
}

const staticNodes = [];
const staticAttributes = [];

function eligibleTextNode(node) {
  const parent = node.parentElement;
  return parent && !parent.closest("script, style, textarea, [data-i18n-ignore]") && node.nodeValue.trim();
}

function rememberStatic(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!eligibleTextNode(node)) continue;
    staticNodes.push({node, source: node.nodeValue});
  }
  for (const element of root.querySelectorAll("[placeholder], [aria-label], [title]")) {
    for (const name of ["placeholder", "aria-label", "title"]) {
      if (element.hasAttribute(name)) staticAttributes.push({element, name, source: element.getAttribute(name)});
    }
  }
}

function translateStatic() {
  document.documentElement.lang = language;
  document.title = translateText("Blaster · Analítica de llamadas");
  for (const item of staticNodes) {
    const leading = item.source.match(/^\s*/)?.[0] || "";
    const trailing = item.source.match(/\s*$/)?.[0] || "";
    const core = item.source.trim().replace(/\s+/g, " ");
    item.node.nodeValue = `${leading}${translateText(core)}${trailing}`;
  }
  for (const item of staticAttributes) item.element.setAttribute(item.name, translateText(item.source));
  for (const selector of document.querySelectorAll("[data-language-selector]")) selector.value = language;
}

export function translateHTML(html) {
  if (language !== "en" || !html) return html;
  const template = document.createElement("template");
  template.innerHTML = html;
  const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.nodeValue.trim() || node.parentElement?.closest("[data-i18n-ignore]")) continue;
    const leading = node.nodeValue.match(/^\s*/)?.[0] || "";
    const trailing = node.nodeValue.match(/\s*$/)?.[0] || "";
    node.nodeValue = `${leading}${translateText(node.nodeValue.trim())}${trailing}`;
  }
  for (const element of template.content.querySelectorAll("[placeholder], [aria-label], [title]")) {
    for (const name of ["placeholder", "aria-label", "title"]) {
      if (element.hasAttribute(name)) element.setAttribute(name, translateText(element.getAttribute(name)));
    }
  }
  return template.innerHTML;
}

export function setLanguage(next) {
  if (!SUPPORTED.has(next) || next === language) return;
  window.dispatchEvent(new CustomEvent("blaster:before-language-change"));
  language = next;
  try { localStorage.setItem(STORAGE_KEY, language); } catch {}
  document.cookie = `blaster_language=${language}; Path=/; Max-Age=31536000; SameSite=Lax`;
  // Reloading guarantees that every data table and regional formatter is rebuilt
  // with the selected locale while the authenticated session remains active.
  window.location.reload();
}

export function initI18n(root = document.body) {
  rememberStatic(root);
  translateStatic();
  for (const selector of document.querySelectorAll("[data-language-selector]")) {
    selector.addEventListener("change", () => setLanguage(selector.value));
  }
}
